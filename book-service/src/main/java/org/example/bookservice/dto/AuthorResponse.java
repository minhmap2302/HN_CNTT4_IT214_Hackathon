package org.example.bookservice.dto;

public class AuthorResponse {

    private Long id;
    private String name;

    public AuthorResponse() {
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
